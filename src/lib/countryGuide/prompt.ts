export function userPrompt(countryHe: string, countryEn: string, units: PromptUnit[]): string {
  return [
    `המדינה: ${countryHe} (${countryEn}).`,
    '',
    'היחידות (מחוזות) שאפשר לבחור מהן ל-provinces:',
    ...units.map((u) => `${u.id} — ${u.name}`),
    '',
    'חפש, ואז כתוב את הסקירה כ-JSON.',
  ].join('\n');
}
